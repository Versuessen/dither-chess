"""CALIBRATION.md from the committed results (no network, no engine)."""

from __future__ import annotations

import json
from pathlib import Path

from .paths import CALIBRATION_MD, RESULTS, lock

TITLES = {"fastelo": "fastelo 7M", "maia3-5m": "Maia-3 5M", "maia3-23m": "Maia-3 23M", "maia2-rapid": "Maia-2 rapid"}


def _load(name: str) -> dict | None:
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{100 * x:.2f}"


def _levels(levels: list[dict]) -> str:
    if not levels:
        return "none"
    ls = [r["level"] for r in levels]
    step = ls[1] - ls[0] if len(ls) > 1 else 0
    return f"{ls[0]}–{ls[-1]}" + (f" (every {step})" if step else "")


def _gauntlet_table(g: dict) -> list[str]:
    out = [
        "| Levels | Gap | Games | Higher: W–D–L | Score | 95% CI | Elo curve | On the curve | Measured gap (95% CI) | Mean plies |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in g["pairings"]:
        out.append(
            f"| {r['low']} v {r['high']} | {r['gap']} | {r['games']} | {r['high_wins']}–{r['draws']}–{r['high_losses']} | {r['score']:.3f} "
            f"| {r['ci95'][0]:.3f}–{r['ci95'][1]:.3f} | {r['expected']:.3f} | {'yes' if r['within_ci'] else '**no**'} "
            f"| {r['elo_diff']:+.0f} ({r['elo_diff_ci95'][0]:+.0f} to {r['elo_diff_ci95'][1]:+.0f}) | {r['mean_plies']} |"
        )
    passed = sum(r["within_ci"] for r in g["pairings"])
    out.append("")
    out.append(f"{passed} of {len(g['pairings'])} pairings lie on the Elo curve within the 95% interval.")
    terms: dict[str, int] = {}
    for r in g["pairings"]:
        for k, v in r["terminations"].items():
            terms[k] = terms.get(k, 0) + v
    out.append("Endings: " + ", ".join(f"{k} {v}" for k, v in sorted(terms.items(), key=lambda kv: -kv[1])) + ".")
    return out


def write_report() -> None:
    meta = _load("positions.meta.json") or {}
    book = _load("book.json") or {}
    sf = lock()["stockfish"]
    src = meta.get("source", {})
    L: list[str] = []
    L += [
        "# Calibration",
        "",
        "How strong DITHER's bots are, measured rather than assumed. **Every rating here is on the Lichess rapid scale**;",
        "no conversion to FIDE ratings is made or implied.",
        "",
        "Generated by `tools/calibrate` (`uv run dither-calibrate report`) from the files in `tools/calibrate/results/`.",
        "",
        "## Summary",
        "",
        "| Bot | Model file | Levels offered | How the levels were set | Gauntlet |",
        "|---|---|---|---|---|",
    ]
    fits = {m: _load(f"{m}.json") for m in ("maia3-5m", "maia3-23m", "maia2-rapid")}
    check = _load("fastelo-check.json")
    gauntlets = {m: _load(f"gauntlet-{m}.json") for m in TITLES}

    def g_summary(m: str) -> str:
        g = gauntlets.get(m)
        if not g:
            return "not run"
        return f"{sum(r['within_ci'] for r in g['pairings'])}/{len(g['pairings'])} pairings on the Elo curve"

    if check:
        L.append(f"| fastelo 7M | {check['variant']}, sha256 `{check['model_sha256'][:12]}` | 600–1900 (every 50) | fastelo's published calibration, checked below | {g_summary('fastelo')} |")
    for m, f in fits.items():
        if f:
            L.append(f"| {TITLES[m]} | {f['variant']}, sha256 `{f['model_sha256'][:12]}` | {_levels(f['levels'])} | {f['method']} | {g_summary(m)} |")
    L += [
        "",
        "## Method",
        "",
        "The bots are matched to people by the quality of their moves, with fastelo's method (`fastelo/calibrate.py`):",
        "on positions from real games, Stockfish scores every legal move; a move's *loss* is how much expected score",
        "it gives away against the best move, using the Lichess expected-score model W = 1 / (1 + e^(−0.00368208·cp)).",
        "Humans of a rating band lose, on average, a certain amount per move; a bot is set so that its own expected",
        "loss per move, Σ p(move) · loss(move) over its sampled move distribution, equals that of the band.",
        "",
        "Then the levels are played against each other (gauntlets) to check that their spacing follows the Elo curve.",
        "",
        "### Data",
        "",
        f"- Games: Lichess open database, {meta.get('month', '?')} (CC0), rated rapid games (Lichess speed classes: base + 40 × increment",
        "  from 8 to 25 minutes), normal or time-forfeit endings, no BOT accounts. This month is later than the training data of every",
        "  model, so the positions are held out.",
        f"- Read: the first {src.get('bytes', 0):,} compressed bytes of `{Path(src.get('url', '')).name}`, SHA-256 `{src.get('sha256', '')}`;"
        f" {meta.get('rapid_clean_games_read', 0):,} rapid games.",
        "- Positions: from ply 10 on, the player to move has at least 30 s left (fastelo's rule), at most one position per player",
        f"  per game, no position twice; {meta.get('rules', {}).get('per_band', '?')} per 200-point band of the mover's pre-game Lichess rapid rating, 600–2400.",
        f"- Stockfish {sf['release'].replace('sf_', '')} (official build, sha256 `{sf['sha256'][:16]}…`), one thread, 20,000 nodes per legal move,",
        "  multi-PV over all moves. Stockfish only scores moves here; it never plays in DITHER.",
        "",
    ]
    if check:
        L += [
            "### Human loss per band",
            "",
            "| Band | Positions | Human loss per move (%) | ± s.e. |",
            "|---|---|---|---|",
        ]
        for b in check["bands"]:
            L.append(f"| {b['band']} | {b['n']} | {_pct(b['human'])} | {_pct(b['human_se'])} |")
        L.append("")

    if check:
        L += [
            "## fastelo (primary bot, 600–1900)",
            "",
            "fastelo plays with its own published calibration, used exactly. On our held-out positions its calibrated policy loses:",
            "",
            "| Band | Human (%) | fastelo calibrated (%) | Difference in standard errors | Rating input | Temperature |",
            "|---|---|---|---|---|---|",
        ]
        for b in check["bands"]:
            L.append(
                f"| {b['band']} | {_pct(b['human'])} | {_pct(b['policy_loss'])} | {b['gap_se']:+.1f} | {b['conditioning']:.0f} | {b['temperature']:.3f} |"
            )
        L.append("")
        if gauntlets.get("fastelo"):
            L += ["### Gauntlet", ""] + _gauntlet_table(gauntlets["fastelo"]) + [""]

    for m, f in fits.items():
        if not f:
            continue
        L += [f"## {TITLES[m]}", ""]
        tc = f["temperature_curve"]
        sched = (
            f"Temperature schedule: {tc['value']:.3f} at {tc['knot']:.0f}, slopes {1000 * tc['slope_lo']:+.3f} / {1000 * tc['slope_hi']:+.3f}"
            f" per 1000 points below / above, clipped to [{tc['t_min']}, {tc['t_max']}]."
        )
        if m == "maia2-rapid":
            L += [
                "Maia-2 takes its rating input in 100-point buckets (below 1100, 1100–1199, …, 2000 and above), so fastelo's",
                "step 3 (a continuous rating-input correction) does not apply. Each band's temperature is matched with the",
                "input in the band centre's bucket, a non-increasing two-segment line is fitted through those (fastelo's step 1),",
                "and every level uses its own bucket with the line's temperature. A level is offered only if a temperature in",
                "[0.3, 1.5] could match its band.",
                "",
                sched,
                "",
                "| Band | Human (%) | Model at its bucket, T = 1 (%) | Temperature matching the band | Schedule | Calibrated (%) | Difference (s.e.) |",
                "|---|---|---|---|---|---|---|",
            ]
            for b in f["bands"]:
                tm = "not reachable" if b["t_match"] is None else f"{b['t_match']:.3f}"
                L.append(
                    f"| {b['band']} | {_pct(b['human'])} | {_pct(b['raw_loss'])} | {tm} | {b['temperature']:.3f} | {_pct(b['policy_loss'])} | {b['gap_se']:+.1f} |"
                )
        else:
            L += [
                sched,
                "",
                "With a few hundred positions per band the human loss of neighbouring bands can differ by less than its",
                "standard error, so the per-band rating inputs can cross. They are made non-decreasing by weighted isotonic",
                "regression (weights 1/s.e.²); both values are shown.",
                "",
                "| Band | Human (%) | Model, input = band, T = 1 (%) | Temperature | Rating input (per band → used) | Offset | Calibrated (%) | Difference (s.e.) | Top-1 match raw → calibrated |",
                "|---|---|---|---|---|---|---|---|---|",
            ]
            for b in f["bands"]:
                c = b["conditioning"]
                raw = b.get("conditioning_raw")
                cin = "not reachable" if c is None else (f"{raw:.0f} → {c:.0f}" if raw is not None and round(raw) != round(c) else f"{c:.0f}")
                off = "—" if c is None else f"{c - b['elo']:+.0f}"
                L.append(
                    f"| {b['band']} | {_pct(b['human'])} | {_pct(b['raw_loss'])} | {b['temperature']:.3f} | {cin} | {off} "
                    f"| {_pct(b['policy_loss'])} | {b['gap_se']:+.1f} | {100 * b['raw_top1']:.1f}% → {100 * b['cal_top1']:.1f}% |"
                )
        L += ["", f"Levels offered: {_levels(f['levels'])}.", ""]
        if gauntlets.get(m):
            L += ["### Gauntlet", ""] + _gauntlet_table(gauntlets[m]) + [""]

    L += [
        "## Gauntlets",
        "",
        f"Each pairing plays {len(book.get('openings', []))} openings twice with colours swapped ({2 * len(book.get('openings', []))} games). The openings are the",
        f"first {book.get('plies', 8)} plies of games between players rated 1600 or more, kept when Stockfish at {book.get('nodes', 0):,} nodes",
        f"puts them within {book.get('max_cp', 35)} centipawns of equality. Bots play exactly as in the app: one forward pass",
        "per move, sampling at the level's temperature, draw claims when not better, rare resignation, and the FIDE",
        "automatic endings (fivefold repetition, 75 moves, dead positions by material).",
        "",
        "The expected score of the stronger level on the Elo curve is 1 / (1 + 10^(−gap/400)). Its 95% interval is",
        "score ± 1.96 standard errors, from the scores of the 200 game pairs (one opening, both colours).",
        "",
        "These games test the spacing between levels of one bot. The absolute level comes from the human data above.",
        "",
        "## Limitations",
        "",
        "- The positions come from the first hours of one month of Lichess rapid games.",
        "- Matching expected loss per move matches how much a level gives away, not every aspect of style.",
        "- A bot that matches humans move by move can still score differently against people than people do against each",
        "  other (bots do not tire, tilt or flag); the levels are a calibrated estimate, not a guarantee.",
        "",
        "## Reproduce",
        "",
        "```sh",
        "cd tools/calibrate",
        "uv run dither-calibrate all        # positions, Stockfish analysis, book, caches, fits, gauntlets, this file",
        "cd ../models && uv run dither-models pack   # put the Maia calibrations into the packs",
        "```",
        "",
    ]
    CALIBRATION_MD.write_text("\n".join(L))
    print(f"wrote {CALIBRATION_MD}", flush=True)
